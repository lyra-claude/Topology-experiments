#!/usr/bin/env python3
"""
analyze_diverse_seed.py — RAW metric extraction for the diverse-seed experiment.

Reports (NO adjudication — Lyra adjudicates against the pre-registration):
  (i)   full mean leaf-within-diversity trajectory (mean over 30 seeds per gen)
  (ii)  peak generation, (iii) peak value, (iv) long-run floor (final gen mean),
  (v)   decay rate from peak to floor (absolute drop, fractional drop, per-gen slope)
  + monotone vs non-monotone OBSERVATION per condition.

Estimand: leafWithinDiv column = exact mean pairwise Hamming within each leaf,
averaged over the 4 leaves. Per-seed trajectories are averaged over seeds at
each generation, then metrics are read off the seed-averaged trajectory.

Writes results/diverse_seed/METRICS.md and prints the same.
"""
import csv
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(HERE, "results", "diverse_seed")
TOPOLOGIES = ["star_hub_out", "star_hub_in", "star_undirected"]
DOMAINS = ["nk4", "onemax"]
OUT_MD = os.path.join(RESULTS_DIR, "METRICS.md")


def load_trajectories(domain, topo, col="leafWithinDiv"):
    """Return (gens, matrix[seed, gen]) for the given column across all seeds."""
    topo_dir = os.path.join(RESULTS_DIR, domain, topo)
    gens = None
    rows = []
    for fn in sorted(os.listdir(topo_dir),
                     key=lambda s: int(s.replace("seed", "").replace(".csv", ""))):
        if not fn.endswith(".csv"):
            continue
        with open(os.path.join(topo_dir, fn), newline="") as f:
            data = list(csv.DictReader(f))
        g = [int(r["generation"]) for r in data]
        v = [float(r[col]) for r in data]
        if gens is None:
            gens = g
        rows.append(v)
    return np.array(gens), np.array(rows)  # (n_gen,), (n_seed, n_gen)


def metrics_for(gens, mat):
    """Compute peak/floor/decay metrics from the seed-averaged trajectory."""
    mean_traj = mat.mean(axis=0)             # mean over seeds per generation
    peak_idx = int(np.argmax(mean_traj))
    peak_gen = int(gens[peak_idx])
    peak_val = float(mean_traj[peak_idx])
    floor_val = float(mean_traj[-1])
    floor_gen = int(gens[-1])
    abs_drop = peak_val - floor_val
    frac_drop = abs_drop / peak_val if peak_val > 0 else float("nan")
    span = floor_gen - peak_gen
    slope = (floor_val - peak_val) / span if span > 0 else float("nan")

    # monotone check on the seed-averaged trajectory
    diffs = np.diff(mean_traj)
    rises = np.any(diffs > 1e-6)
    falls = np.any(diffs < -1e-6)
    if rises and falls:
        # distinguish "rise then fall" from noisy
        # non-monotone if there is a strict interior peak
        interior_peak = 0 < peak_idx < len(mean_traj) - 1
        shape = "NON-MONOTONE (rise then decay)" if interior_peak else "non-monotone (mixed)"
    elif rises and not falls:
        shape = "monotone rise"
    elif falls and not rises:
        shape = "monotone decay"
    else:
        shape = "flat"

    return {
        "mean_traj": mean_traj,
        "peak_gen": peak_gen,
        "peak_val": peak_val,
        "floor_val": floor_val,
        "floor_gen": floor_gen,
        "abs_drop": abs_drop,
        "frac_drop": frac_drop,
        "peak_to_floor_slope_per_gen": slope,
        "shape": shape,
    }


def fmt_traj(gens, mean_traj, every=1):
    pts = [f"({int(g)},{v:.4f})" for g, v in zip(gens[::every], mean_traj[::every])]
    return " ".join(pts)


def main():
    md = ["# Diverse-Seed Experiment — RAW Metrics\n",
          "Generated by `experiments/analyze_diverse_seed.py`. RAW metrics only; "
          "no adjudication.\n",
          "Estimand: `leafWithinDiv` = exact mean pairwise Hamming within each leaf, "
          "averaged over 4 leaves. Trajectories averaged over 30 seeds (0-29) per "
          "generation checkpoint; metrics read off the seed-averaged trajectory.\n"]

    for domain in DOMAINS:
        md.append(f"\n## Domain: {domain}\n")
        md.append("| Condition | peak gen | peak val | floor (gen 500) | abs drop | "
                  "frac drop | slope/gen (peak→floor) | shape |")
        md.append("|---|---|---|---|---|---|---|---|")
        traj_lines = []
        for topo in TOPOLOGIES:
            gens, mat = load_trajectories(domain, topo)
            m = metrics_for(gens, mat)
            md.append(
                f"| {topo} | {m['peak_gen']} | {m['peak_val']:.4f} | "
                f"{m['floor_val']:.4f} | {m['abs_drop']:.4f} | "
                f"{m['frac_drop']:.3f} | {m['peak_to_floor_slope_per_gen']:.2e} | "
                f"{m['shape']} |"
            )
            traj_lines.append(f"\n**{topo}** mean leaf-within trajectory "
                              f"(every 20 gens):\n\n{fmt_traj(gens, m['mean_traj'], every=2)}\n")
            print(f"[{domain}] {topo}: peak gen={m['peak_gen']} val={m['peak_val']:.4f} "
                  f"floor={m['floor_val']:.4f} drop={m['abs_drop']:.4f} "
                  f"frac={m['frac_drop']:.3f} slope={m['peak_to_floor_slope_per_gen']:.2e} "
                  f"[{m['shape']}]")
        md.extend(traj_lines)

    with open(OUT_MD, "w") as f:
        f.write("\n".join(md))
    print(f"\nWrote {OUT_MD}")


if __name__ == "__main__":
    main()
